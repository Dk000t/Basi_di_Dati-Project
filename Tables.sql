CREATE TABLE UTENTE (
    USERNAME VARCHAR2(20) PRIMARY KEY,
    EMAIL VARCHAR2(50) UNIQUE NOT NULL,
    DATA_ISCRIZIONE DATE NOT NULL
);

CREATE TABLE COMMUNITY (
    NOME_COMMUNITY VARCHAR2(20) PRIMARY KEY,
    USERNAME VARCHAR2(20) NOT NULL,
    DATA_CREAZIONE DATE NOT NULL,
    CONSTRAINT FK_COMMUNITY_OWNER FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME)
);

CREATE TABLE POST (
    NOME_COMMUNITY VARCHAR2(20),
    CODICE_POST NUMBER,
    TITOLO_POST VARCHAR2(100) NOT NULL,
    USERNAME VARCHAR2(20) NOT NULL,
    DATA_PUBBLICAZIONE DATE NOT NULL,
    PRIMARY KEY(NOME_COMMUNITY, CODICE_POST),
    CONSTRAINT FK_POST_COMMUNITY FOREIGN KEY (NOME_COMMUNITY) REFERENCES COMMUNITY(NOME_COMMUNITY),
    CONSTRAINT FK_POST_OWNER FOREIGN KEY(USERNAME) REFERENCES UTENTE(USERNAME)
);

CREATE TABLE GRUPPO (
    NOME_GRUPPO VARCHAR2(20) PRIMARY KEY,
    USERNAME VARCHAR2(20) NOT NULL,
    DATA_CREAZIONE DATE NOT NULL,
    CONSTRAINT FK_GROUP_OWNER FOREIGN KEY(USERNAME) REFERENCES UTENTE(USERNAME)
);

CREATE TABLE E_AMICO_DI (
    USERNAME_1 VARCHAR2(20),
    USERNAME_2 VARCHAR2(20),
    DATA_INIZIO DATE NOT NULL,
    PRIMARY KEY(USERNAME_1, USERNAME_2),
    CONSTRAINT FK_AMICO_USER_1 FOREIGN KEY (USERNAME_1) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_AMICO_USER_2 FOREIGN KEY (USERNAME_2) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE
);

CREATE TABLE SEGUE (
    USERNAME VARCHAR2(20),
    NOME_COMMUNITY VARCHAR2(20),
    DATA_ISCRIZIONE DATE NOT NULL,
    PRIMARY KEY(USERNAME, NOME_COMMUNITY),
    CONSTRAINT FK_SEGUE_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_SEGUE_COMMUNITY FOREIGN KEY (NOME_COMMUNITY) REFERENCES COMMUNITY(NOME_COMMUNITY) ON DELETE CASCADE
);

CREATE TABLE FA_PARTE (
    USERNAME VARCHAR2(20),
    NOME_GRUPPO VARCHAR2(20),
    DATA_ADESIONE DATE NOT NULL,
    PRIMARY KEY(USERNAME, NOME_GRUPPO),
    CONSTRAINT FK_FA_PARTE_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_FA_PARTE_GRUPPO FOREIGN KEY (NOME_GRUPPO) REFERENCES GRUPPO(NOME_GRUPPO) ON DELETE CASCADE
);

CREATE TABLE CASA_SVILUPPATRICE (
    NOME_SVILUPPATORE VARCHAR2(20) PRIMARY KEY,
    ANNO_FONDAZIONE_SVILUPPATORE NUMBER(4,0) NOT NULL,
    NAZIONALITA_SVILUPPATORE VARCHAR2(20) NOT NULL
);

CREATE TABLE EDITORE (
    NOME_EDITORE VARCHAR2(20) PRIMARY KEY,
    ANNO_FONDAZIONE_EDITORE NUMBER(4,0) NOT NULL,
    NAZIONALITA_EDITORE VARCHAR2(20) NOT NULL
);

CREATE TABLE GIOCO (
    NOME_GIOCO VARCHAR2(20) PRIMARY KEY,
    DATA_RILASCIO DATE NOT NULL,
    GENERE VARCHAR2(20) NOT NULL,
    PREZZO NUMBER(4,0) NOT NULL,
    NOME_SVILUPPATORE VARCHAR2(20) NOT NULL,
    NOME_EDITORE VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_GIOCO_EDITORE FOREIGN KEY (NOME_EDITORE) REFERENCES EDITORE(NOME_EDITORE) ON DELETE CASCADE,
    CONSTRAINT FK_GIOCO_SVILUPPATORE FOREIGN KEY (NOME_SVILUPPATORE) REFERENCES CASA_SVILUPPATRICE(NOME_SVILUPPATORE) ON DELETE CASCADE
);

CREATE TABLE LISTA_DESIDERI (
    USERNAME VARCHAR2(20) PRIMARY KEY,
    NOME_GIOCO VARCHAR2(20) NOT NULL,
    DATA_INSERIMENTO DATE NOT NULL,
    CONSTRAINT FK_DESIDERI_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_DESIDERI_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE COLLEZIONABILE (
    CODICE_COLLEZIONABILE NUMBER(12,0),
    NOME_COLLEZIONABILE VARCHAR2(20) NOT NULL,
    NOME_GIOCO VARCHAR2(20),
    CONSTRAINT PK_COLLEZIONABILE PRIMARY KEY (CODICE_COLLEZIONABILE, NOME_GIOCO),
    CONSTRAINT FK_COLLEZIONABILE_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE OTTIENE_COLLEZIONABILE (
    CODICE_COLLEZIONABILE NUMBER(12,0),
    USERNAME VARCHAR2(20),
    DATA_OTTENIMENTO_COLLEZIONABILE DATE NOT NULL,
    PRIMARY KEY (CODICE_COLLEZIONABILE, USERNAME),
    CONSTRAINT FK_OTTIENE_COLLEZIONABILE_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_OTTIENE_COLLEZIONABILE_COLLEZIONABILE FOREIGN KEY (CODICE_COLLEZIONABILE) REFERENCES COLLEZIONABILE(CODICE_COLLEZIONABILE) ON DELETE CASCADE
);

CREATE TABLE OBIETTIVO (
    CODICE_OBIETTIVO NUMBER(10,0),
    NOME_OBIETTIVO VARCHAR2(20) NOT NULL,
    NOME_GIOCO VARCHAR2(20),
    CONSTRAINT PK_OBIETTIVO PRIMARY KEY (CODICE_OBIETTIVO, NOME_GIOCO),
    CONSTRAINT FK_OBIETTIVO_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE RAGGIUNGE_OBIETTIVO (
    CODICE_OBIETTIVO NUMBER(10,0),
    USERNAME VARCHAR2(20), 
    DATA_OTTENIMENTO_OBIETTIVO DATE NOT NULL,
    PRIMARY KEY (CODICE_OBIETTIVO, USERNAME),
    CONSTRAINT FK_RAGGIUNGE_OBIETTIVO_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_RAGGIUNGE_OBIETTIVO_OBIETTIVO FOREIGN KEY (CODICE_OBIETTIVO) REFERENCES OBIETTIVO(CODICE_OBIETTIVO) ON DELETE CASCADE
);

CREATE TABLE RECENSIONE (
    COD_RECENSIONE NUMBER(7,0) PRIMARY KEY,
    TITOLO_RECENSIONE VARCHAR2(20) NOT NULL,
    VOTO_RECENSIONE NUMBER NOT NULL,
    USERNAME VARCHAR2(20) NOT NULL,
    NOME_GIOCO VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_RECENSIONE_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_RECENSIONE_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE PAGAMENTO (
    CODICE_RICEVUTA_PAGAMENTO NUMBER PRIMARY KEY,
    DATA_PAGAMENTO DATE NOT NULL,
    METODO_DI_PAGAMENTO VARCHAR2(20) NOT NULL CHECK (METODO_DI_PAGAMENTO IN ('CARTA', 'PAYPAL')),
    IMPORTO_PAGAMENTO NUMBER NOT NULL,
    USERNAME VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_PAGAMENTO_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE
);

CREATE TABLE KEY_GIOCO (
    CODICE_GIOCO NUMBER PRIMARY KEY,
    DATA_SCADENZA DATE NOT NULL,
    USERNAME VARCHAR2(20) NOT NULL,
    NOME_GIOCO VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_KEY_GIOCO_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_KEY_GIOCO_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE DLC (
    NOME_DLC VARCHAR2(20) PRIMARY KEY,
    DATA_RILASCIO_DLC DATE NOT NULL,
    PREZZO_DLC NUMBER NOT NULL,
    NOME_GIOCO VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_DLC_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE RISCATTA_DLC (
    USERNAME VARCHAR2(20) NOT NULL,
    NOME_DLC VARCHAR2(20),
    CODICE_RICEVUTA_PAGAMENTO NUMBER,
    PRIMARY KEY (USERNAME, NOME_DLC, CODICE_RICEVUTA_PAGAMENTO),
    FOREIGN KEY (NOME_DLC) REFERENCES DLC(NOME_DLC),
    FOREIGN KEY (CODICE_RICEVUTA_PAGAMENTO) REFERENCES PAGAMENTO(CODICE_RICEVUTA_PAGAMENTO),
    FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME)
);

CREATE TABLE RISCATTA_GIOCO (
    NOME_GIOCO VARCHAR2(20),
    CODICE_RICEVUTA_PAGAMENTO NUMBER,
    USERNAME VARCHAR2(20) NOT NULL,
    PRIMARY KEY (NOME_GIOCO, CODICE_RICEVUTA_PAGAMENTO),
    FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO),
    FOREIGN KEY (CODICE_RICEVUTA_PAGAMENTO) REFERENCES PAGAMENTO(CODICE_RICEVUTA_PAGAMENTO),
    FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME)
);
