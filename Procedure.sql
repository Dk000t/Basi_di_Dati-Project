CREATE OR REPLACE PROCEDURE PUBBLICA_POST(NOMECOMM VARCHAR,NOME_UTENTE VARCHAR ,TITOLO_POST VARCHAR,STATO_POST VARCHAR)
IS 
    CODICEPOST NUMBER(7);
    NOMEUTENTE VARCHAR(20);
    NOMECOMMUNITY VARCHAR(20);
BEGIN
    CODICEPOST := TO_CHAR(DBMS_RANDOM.VALUE(0000000,9999999));
SELECT NOME_COMMUNITY INTO NOMECOMMUNITY
FROM COMMUNITY
WHERE NOME_COMMUNITY = NOMECOMM;
SELECT USERNAME INTO NOMEUTENTE
FROM UTENTE
WHERE USERNAME = NOME_UTENTE; 
INSERT INTO POST(NOME_COMMUNITY, CODICE_POST, TITOLO_POST, USERNAME, DATA_PUBBLICAZIONE, STATO_POST)
VALUES (NOMECOMMUNITY, CODICEPOST, TITOLO_POST, NOMEUTENTE, SYSDATE, STATO_POST);
COMMIT; 
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
    	RAISE_APPLICATION_ERROR(-20500,'IMMISSIONE DATI ERRATA, RICONTROLLA I DATI');
    WHEN DUP_VAL_ON_INDEX THEN
            CODICEPOST := TO_CHAR(DBMS_RANDOM.VALUE(0000000,9999999));
    INSERT INTO POST(NOME_COMMUNITY,CODICE_POST,TITOLO_POST,USERNAME,DATA_PUBBLICAZIONE,STATO_POST)
    VALUES (NOMECOMMUNITY, CODICEPOST,TITOLO_POST,NOMEUTENTE,SYSDATE,STATO_POST);
END;
