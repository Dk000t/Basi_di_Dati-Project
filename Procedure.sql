--PUBBLICA POST IN COMMUNITY (CONTROLLA DOMANI)

CREATE OR REPLACE PROCEDURE PUBBLICA_POST(NOMECOMM VARCHAR,NOME_UTENTE VARCHAR ,TITOLO_post VARCHAR)
IS 
    CODICEPOST NUMBER(7);
    NOMEUTENTE CHAR(100);
    NOMECOMMUNITY CHAR(100);
    TITOLOPOST CHAR(100);
BEGIN
    CODICEPOST :=DBMS_RANDOM.VALUE(0000000,9999999);

--PRENDO IL NOME COMMUNITY
SELECT NOME_COMMUNITY INTO NOMECOMMUNITY
FROM COMMUNITY
WHERE NOME_COMMUNITY = NOMECOMM;
--PRENDO IL NOME UTENTE 
SELECT USERNAME INTO NOMEUTENTE
FROM UTENTE
WHERE USERNAME = NOME_UTENTE; 
--titolo post
SELECT TITOLO_POST INTO TITOLOPOST
FROM POST
WHERE TITOLO_POST = TITOLO_post;
--POST
INSERT INTO POST(NOME_COMMUNITY,CODICE_POST,TITOLO_POST,USERNAME,DATA_PUBBLICAZIONE,CHECK_POST)
VALUES (NOMECOMMUNITY, CODICEPOST,TITOLO_post,NOME_UTENTE,SYSDATE,CHECK_COMMUNITY);
COMMIT; --COMMIT DELLA PROCEDURA


    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            CODICEPOST :=DBMS_RANDOM.VALUE(0000000,9999999);
    INSERT INTO POST(NOME_COMMUNITY,CODICE_POST,TITOLO_POST,USERNAME,DATA_PUBBLICAZIONE,CHECK_POST)
    VALUES (NOMECOMMUNITY, CODICEPOST,TITOLO_POST,NOMEUTENTE,SYSDATE,CHECK_COMMUNITY);
END;


