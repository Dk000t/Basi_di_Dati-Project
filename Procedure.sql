--RECENSIONE GIOCO  (CONTROLLA DOMANI)

CREATE OR REPLACE PROCEDURE RECENSIONE_GIOCO (NOME_UTENTE VARCHAR,NOME_GIOCO VARCHAR,TITOLO_RECENSIONE VARCHAR, VOTO_RECENSIONE NUMBER)
IS 
    CODICE_RECENSIONE NUMBER(7);
    NOMEUTENTE VARCHAR(100);
    NOMEGIOCO VARCHAR(100);
    TITOLORECENSIONE VARCHAR(100);
	VOTORECENSIONE NUMBER(2);
BEGIN
    CODICE_RECENSIONE := DBMS_RANDOM.VALUE(0000000,9999999);
    
    SELECT USERNAME INTO NOMEUTENTE
    FROM UTENTE
    WHERE USERNAME = NOME_UTENTE;
   
    SELECT NOME_GIOCO INTO NOMEGIOCO
    FROM GIOCO
    WHERE NOME_GIOCO = NOMEGIOCO;
    
    SELECT TITOLO INTO TITOLORECENSIONE
    FROM RECENSIONE
    WHERE TITOLO = TITOLO_RECENSIONE;

	SELECT VOTO INTO VOTORECENSIONE
	FROM RECENSIONE
    WHERE VOTO = VOTO_RECENSIONE;
   
    INSERT INTO RECENSIONE( COD_RECENSIONE, TITOLO, VOTO,USERNAME, NOME_GIOCO, DATA_RECENSIONE)
    VALUES (CODICE_RECENSIONE, TITOLORECENSIONE, VOTO_RECENSIONE, NOMEUTENTE, NOMEGIOCO ,SYSDATE);
    COMMIT;

    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            CODICE_RECENSIONE :=DBMS_RANDOM.VALUE(0000000,9999999);
    	INSERT INTO RECENSIONE(COD_RECENSIONE, TITOLO ,VOTO,USERNAME, NOME_GIOCO, DATA_RECENSIONE)
    	VALUES (CODICE_RECENSIONE, TITOLO_RECENSIONE, VOTO_RECENSIONE, NOMEUTENTE,NOMEGIOCO,SYSDATE);
END;


