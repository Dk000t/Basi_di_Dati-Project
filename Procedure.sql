--RECENSIONE GIOCO

CREATE OR REPLACE PROCEDURE RECENSIONE_GIOCO (NOME_UTENTE CHAR,NOME_GIOCO CHAR,TITOLO_RECENSIONE CHAR, VOTO_RECENSIONE NUMBER)
IS 
    CODICE_RECENSIONE NUMBER(7);
    NOMEUTENTE(100);
    TITOLORECENSIONE(100);
BEGIN
    CODICE_RECENSIONE :=DBMS_RANDOM.VALUE(0000000,9999999);
    --TROVO IL NOME UTENTE
    SELECT USERNAME INTO NOMEUTENTE
    FROM UTENTE
    WHERE USERNAME = NOME_UTENTE;
    --TITOLO RECENSIONE
    SELECT TITOLO INTO TITOLORECENSIONE
    FROM RECENSIONE
    WHERE TITOLO = TITOLO_RECENSIONE;
    --INSERIMENTO RECENSIONE
    INSERT INTO RECENSIONE( COD_RECENSIONE, TITOLO, VOTO,USERNAME, NOME_GIOCO, DATA_RECENSIONE)
    VALUES (CODICE_RECENSIONE,TITOLORECENSIONE,VOTO_RECENSIONE,NOME_UTENTE,SYSDATE);

    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            CODICE_RECENSIONE :=DBMS_RANDOM.VALUE(0000000,9999999);
    INSERT INTO RECENSIONE(COD_RECENSIONE, TITOLO ,VOTO,USERNAME, NOME_GIOCO, DATA_RECENSIONE)
    VALUES (CODICE_RECENSIONE,TITOLO_RECENSIONE,VOTO_RECENSIONE,NOMEUTENTE,SYSDATE);
END;


--PUBBLICA POST IN COMMUNITY

CREATE OR REPLACE PROCEDURE PUBBLICA_POST(NOMECOMM CHAR,NOME_UTENTE CHAR ,TITOLO_post CHAR)
IS 
    CODICEPOST NUMBER(7);
    NOMEUTENTE CHAR(100);
    NOMECOMMUNITY CHAR(100);
    TITOLOPOST CHAR(100);
BEGIN
    CODICEPOST :=DBMS_RANDOM.VALUE(0000000,9999999);

--PRENDO IL NOME COMMUNITY
SELECT NOME_COMMUNITY INTO NOMECOMMUNITY
FROM COMMUNITY
WHERE NOME_COMMUNITY = NOMECOMM;
--PRENDO IL NOME UTENTE 
SELECT USERNAME INTO NOMEUTENTE
FROM UTENTE
WHERE USERNAME = NOME_UTENTE; 
--titolo post
SELECT TITOLO_POST INTO TITOLOPOST
FROM POST
WHERE TITOLO_POST = TITOLO_post;
--POST
INSERT INTO POST(NOME_COMMUNITY,CODICE_POST,TITOLO_POST,USERNAME,DATA_PUBBLICAZIONE,CHECK_POST)
VALUES (NOMECOMMUNITY, CODICEPOST,TITOLO_post,NOME_UTENTE,SYSDATE,CHECK_COMMUNITY);
COMMIT; --SERVE PER UPDATARE LA TABELLA POST COL NUOVO POST SE NO NON SUCCEDERà NULLA


    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            CODICEPOST :=DBMS_RANDOM.VALUE(0000000,9999999);
    INSERT INTO POST(NOME_COMMUNITY,CODICE_POST,TITOLO_POST,USERNAME,DATA_PUBBLICAZIONE,CHECK_POST)
    VALUES (NOMECOMMUNITY, CODICEPOST,TITOLO_POST,NOMEUTENTE,SYSDATE,CHECK_COMMUNITY);
END;




















