CREATE OR REPLACE PROCEDURE GIOCO_PUBBLICATO(NOME_GIOCO VARCHAR, GENERE VARCHAR, PREZZO NUMBER, NOME_SVILUPPATORE_GIOCO VARCHAR, NOME_EDITORE_GIOCO VARCHAR)
IS
	NOMESVILUPPATORE VARCHAR(30);
	NOMEEDITORE VARCHAR(30);
BEGIN
SELECT NOME_SVILUPPATORE INTO NOMESVILUPPATORE
FROM CASA_SVILUPPATRICE
WHERE NOME_SVILUPPATORE = NOME_SVILUPPATORE_GIOCO;
SELECT NOME_EDITORE INTO NOMEEDITORE
FROM EDITORE
WHERE NOME_EDITORE = NOME_EDITORE_GIOCO;
INSERT INTO GIOCO (NOME_GIOCO, DATA_RILASCIO, GENERE, PREZZO, NOME_SVILUPPATORE, NOME_EDITORE)
VALUES (NOME_GIOCO, SYSDATE, GENERE, PREZZO, NOMESVILUPPATORE, NOMEEDITORE);
COMMIT;
EXCEPTION
	WHEN DUP_VAL_ON_INDEX THEN --ERRORE AVVIENE QUANDO METTI UN GIOCO CON UN NOME UGUALE A UNO DEL POPOLAMENTO (SVILUPPATORE E EDITORE POSSONO ESSERE UGUALI E QUINDI NON PORTANO ERRORI
	RAISE_APPLICATION_ERROR(-20022,'GIOCO GIA ESISTENTE');
END;
