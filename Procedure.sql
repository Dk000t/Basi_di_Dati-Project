--RECENSIONE GIOCO  (FUNZIONA)

CREATE OR REPLACE PROCEDURE RECENSIONE_GIOCO (NOME_UTENTE VARCHAR,NOMEGIOCO_RECENSIONE VARCHAR,TITOLO_RECENSIONE VARCHAR, VOTO_RECENSIONE NUMBER)
IS 
    CODICE_RECENSIONE NUMBER(7);
    NOMEUTENTE VARCHAR(100);
    NOMEGIOCO VARCHAR(100);
BEGIN
    CODICE_RECENSIONE :=DBMS_RANDOM.VALUE(0000000,9999999);
   --prendo il nome utente
    SELECT USERNAME INTO NOMEUTENTE
    FROM UTENTE
    WHERE USERNAME = NOME_UTENTE;
  --prendo il nome gioco
    SELECT NOME_GIOCO INTO NOMEGIOCO
    FROM GIOCO
    WHERE NOME_GIOCO = NOMEGIOCO_RECENSIONE;
   
   
    INSERT INTO RECENSIONE(COD_RECENSIONE, TITOLO, VOTO, USERNAME, NOME_GIOCO, DATA_RECENSIONE)
    VALUES (CODICE_RECENSIONE, TITOLO_RECENSIONE, VOTO_RECENSIONE, NOMEUTENTE, NOMEGIOCO, SYSDATE);
    COMMIT;
    
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            CODICE_RECENSIONE :=DBMS_RANDOM.VALUE(0000000,9999999);
    INSERT INTO RECENSIONE(COD_RECENSIONE, TITOLO ,VOTO,USERNAME, NOME_GIOCO, DATA_RECENSIONE)
    VALUES (CODICE_RECENSIONE, TITOLO_RECENSIONE, VOTO_RECENSIONE, NOMEUTENTE, NOMEGIOCO, SYSDATE);
END;

