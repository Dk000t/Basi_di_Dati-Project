--Aggiunta di un amico
CREATE OR REPLACE PROCEDURE AGGIUNTA_AMICO (NOME1 VARCHAR, NOME2 VARCHAR)
IS
NOME_UTENTE VARCHAR(100);
NOME_AMICO  VARCHAR(100);

BEGIN
    --TROVO L'EMAIL UTENTE
    SELECT USERNAME INTO NOME_UTENTE
    FROM UTENTE
    WHERE USERNAME = NOME1;
    --TROVO L'EMAIL DELL'AMICO
    SELECT USERNAME INTO NOME_AMICO
    FROM UTENTE
    WHERE USERNAME = NOME2;
    --INSERISCO NELLA TABELLA E' AMICO DI
    INSERT INTO E_AMICO_DI(USERNAME_1,USERNAME_2,DATA_INIZIO)
    VALUES (NOME1,NOME2,SYSDATE);

    EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20015,'UTENTE NON TROVATO');
END;

--ACQUISTA UN GIOCO
CREATE OR REPLACE PROCEDURE ACQUISTA_GIOCO (NOME_UTENTE CHAR, NOMEGIOCO CHAR,IMPORTO NUMBER, METODO_PAGAMENTO CHAR)
IS
    CODICE_PAGAMENTO NUMBER(12);
    NOME_USER VARCHAR(100);
BEGIN
    CODICE_PAGAMENTO := DBMS_RANDOM.VALUE(100000000000,999999999999);

    --TROVO NOME UTENTE
    SELECT USERNAME INTO NOME_USER
    FROM UTENTE
    WHERE USERNAME = NOME_UTENTE;
    --INSERIMENTO DEL PAGAMENTO
    INSERT INTO PAGAMENTO (CODICE_RICEVUTA_PAGAMENTO,DATA_PAGAMENTO,METODO_DI_PAGAMENTO,IMPORTO,USERNAME)
    VALUES(CODICE_PAGAMENTO,SYSDATE, METODO_PAGAMENTO,IMPORTO,NOME_USER);
    --RISCATTA GIOCO
    INSERT INTO RISCATTA_GIOCO (USERNAME, NOME_GIOCO,CODICE_RICEVUTA_PAGAMENTO)
    VALUES(NOME_USER, NOME_GIOCO,CODICE_PAGAMENTO);

    EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN  --In caso ci fosse un duplicato di codice pagamento lo si ricrea
        CODICE_PAGAMENTO := DBMS_RANDOM.VALUE(100000000000,);
    INSERT INTO RISCATTA_GIOCO (USERNAME, NOME_GIOCO,CODICE_RICEVUTA_PAGAMENTO)
    VALUES(NOME_USER, NOME_GIOCO,CODICE_PAGAMENTO);
END;


