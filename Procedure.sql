--AQUISTA UN DLC
CREATE OR REPLACE PROCEDURE ACQUISTO_DLC (NOME_UTENTE VARCHAR, NOMEDLC_ACQ VARCHAR, IMPORTO NUMBER, METODO_PAGAMENTO VARCHAR)
IS

    CODICE_PAGAMENTO_DLC NUMBER(12);
    NOMEUTENTE VARCHAR(100);
    NOMEDLC VARCHAR(100);
BEGIN
    CODICE_PAGAMENTO_DLC := DBMS_RANDOM.VALUE(000000000000,999999999999);
    --PRENDO UTENTE
    SELECT USERNAME INTO NOMEUTENTE
    FROM UTENTE
    WHERE USERNAME = NOME_UTENTE;
    --PRENDO NOME DLC
    SELECT NOME_DLC INTO NOMEDLC
    FROM DLC
    WHERE NOME_DLC = NOMEDLC_ACQ;
    --INSERISCO PAGAMENTO E RISCATTO DLC
    INSERT INTO PAGAMENTO (CODICE_RICEVUTA_PAGAMENTO, DATA_PAGAMENTO, METODO_DI_PAGAMENTO, IMPORTO, USERNAME)
    VALUES(CODICE_PAGAMENTO_DLC, SYSDATE , METODO_PAGAMENTO, IMPORTO,NOMEUTENTE);
  
    INSERT INTO RISCATTA_DLC (NOME_DLC,CODICE_RICEVUTA_PAGAMENTO)
    VALUES(NOMEDLC,CODICE_PAGAMENTO_DLC);


    EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN --IN CASO CI FOSSE UN DUPLICATO
        CODICE_PAGAMENTO_DLC := DBMS_RANDOM.VALUE(000000000000,999999999999); 

    INSERT INTO PAGAMENTO (CODICE_RICEVUTA_PAGAMENTO,DATA_PAGAMENTO,METODO_DI_PAGAMENTO,IMPORTO,USERNAME)
    VALUES(CODICE_PAGAMENTO_DLC,SYSDATE,METODO_PAGAMENTO,IMPORTO,NOMEUTENTE);

	INSERT INTO RISCATTA_DLC (NOME_DLC,CODICE_RICEVUTA_PAGAMENTO)
    VALUES(NOMEDLC,CODICE_PAGAMENTO_DLC);
	
END; 




