--ACQUISTA UN GIOCO
CREATE OR REPLACE PROCEDURE ACQUISTA_GIOCO (NOME_UTENTE VARCHAR, NOMEGIOCO_ACQ VARCHAR,METODO_PAGAMENTO VARCHAR,IMPORTO NUMBER)
IS
    CODICE_PAGAMENTO NUMBER(12);
    NOMEGIOCO VARCHAR(100);
    NOMEUTENTE VARCHAR(100);
    
BEGIN
    CODICE_PAGAMENTO := DBMS_RANDOM.VALUE(000000000000,999999999999);

    --NOME GIOCO
    SELECT NOME_GIOCO INTO NOMEGIOCO
    FROM GIOCO
    WHERE NOME_GIOCO = NOMEGIOCO_ACQ;
    --NOME UTENTE
    SELECT USERNAME INTO NOMEUTENTE
    FROM UTENTE 
    WHERE USERNAME = NOME_UTENTE;
    --INSERIMENTO DEL PAGAMENTO
    INSERT INTO PAGAMENTO (CODICE_RICEVUTA_PAGAMENTO, DATA_PAGAMENTO, METODO_DI_PAGAMENTO, IMPORTO,USERNAME)
    VALUES(CODICE_PAGAMENTO, SYSDATE, METODO_PAGAMENTO,IMPORTO,NOMEUTENTE);
    --RISCATTA GIOCO
    INSERT INTO RISCATTA_GIOCO (NOME_GIOCO,CODICE_RICEVUTA_PAGAMENTO)
    VALUES(NOMEGIOCO ,CODICE_PAGAMENTO);

    EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN  --In caso ci fosse un duplicato di codice pagamento lo si ricrea
        CODICE_PAGAMENTO := DBMS_RANDOM.VALUE(000000000000,999999999999);
    INSERT INTO RISCATTA_GIOCO (NOME_GIOCO,CODICE_RICEVUTA_PAGAMENTO)
    VALUES(NOMEGIOCO,CODICE_PAGAMENTO);
END;

