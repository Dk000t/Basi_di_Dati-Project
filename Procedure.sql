    INSERT INTO RECENSIONE(COD_RECENSIONE,TITOLO,VOTO,USERNAME,NOME_GIOCO,DATA_RECENSIONE)
    VALUES (CODICE_RECENSIONE,TITOLO_RECENSIONE,VOTO_RECENSIONE,NOME_UTENTE,SYSDATE);

