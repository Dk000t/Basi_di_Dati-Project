-- Visualizza i giochi ordinati per voto medio di recensione.
CREATE OR REPLACE VIEW VISTA_GIOCHI_ORDINATI AS
SELECT NOME_GIOCO, AVG(VOTO) AS VOTO_MEDIO, COUNT(*) AS NUM_RECENSIONI
FROM RECENSIONE
GROUP BY NOME_GIOCO
ORDER BY AVG(VOTO) DESC, COUNT(*) DESC;

% SELECT * FROM VISTA_GIOCHI_ORDINATI;

--Vista dei giochi piu comprati.
CREATE OR REPLACE VIEW VISTA_GIOCHI_PIU_COMPRATI AS
SELECT RG.NOME_GIOCO, COUNT(*) AS NUM_ACQUISTI
FROM RISCATTA_GIOCO RG
JOIN PAGAMENTO P ON RG.CODICE_RICEVUTA_PAGAMENTO = P.CODICE_RICEVUTA_PAGAMENTO
GROUP BY RG.NOME_GIOCO
ORDER BY COUNT(*) DESC;

% SELECT * FROM VISTA_GIOCHI_PIU_COMPRATI;

--Vista Sviluppatore con piu giochi sviluppati.
CREATE OR REPLACE VIEW VISTA_NUMERO_GIOCHI_SVILUPPATORE AS
SELECT NOME_SVILUPPATORE, COUNT(*) AS NUMERO_GIOCHI_SVILUPPATI
FROM GIOCO
GROUP BY NOME_SVILUPPATORE
ORDER BY COUNT(*) DESC;

SELECT * FROM VISTA_NUMERO_GIOCHI_SVILUPPATORE;

--Vista con Editore con piu giochi pubblicati.
CREATE OR REPLACE VIEW VISTA_NUMERO_GIOCHI_EDITORE AS
SELECT NOME_EDITORE, COUNT(*) AS NUMERO_GIOCHI_PUBBLICATI
FROM GIOCO
GROUP BY NOME_EDITORE
ORDER BY COUNT(*) DESC;

% SELECT * FROM VISTA_NUMERO_GIOCHI_EDITORE;


