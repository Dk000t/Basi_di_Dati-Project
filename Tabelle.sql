CREATE TABLE GIOCO{
    NOME_GIOCO VARCHAR(50),
    DATA_RILASCIO DATE NOT NULL,
    GENERE VARCHAR(20) NOT NULL,
    PREZZO NUMBER(4,0) NOT NULL,
    NOME_SVILUPPATORE VARCHAR(50) UNIQUE NOT NULL,
    NOME_EDITORE VARCHAR(50) UNIQUE NOT NULL,

    CONSTRAINT PK_GIOCO PRIMARY KEY (NOME_GIOCO),
    CONSTRAINT FK_EDITORE FOREIGN KEY (NOME_EDITORE) REFERENCES EDITORE(NOME_EDITORE) ON DELETE CASCADE,
    CONSTRAINT FK_CASA_SVIlUPPATRICE FOREIGN KEY (NOME_SVILUPPATORE) REFERENCES CASA_SVILUPPATRICE(NOME_SVILUPPATORE) ON DELETE CASCADE
} 

CREATE TABLE CASA_SVILUPPATRICE {
    NOME_SVILUPPATORE VARCHAR(50),
    ANNO_FONDAZIONE_SVILUPPATORE NUMBER (4,0) NOT NULL,
    NAZIONALITA_SVILUPPATORE VARCHAR(50) NOT NULL,

    CONSTRAINT PK_CASA_SVILUPPATRICE PRIMARY KEY (NOME_SVILUPPATORE)    
}

CREATE TABLE EDITORE{
    NOME_EDITORE VARCHAR(50),
    ANNO_FONDAZIONE_EDITORE NUMBER (4,0) NOT NULL,
    NAZIONALITA_EDITORE VARCHAR(50) NOT NULL,

    CONSTRAINT PK_EDITORE PRIMARY KEY (NOME_EDITORE)
}

CREATE TABLE COLLEZIONABILE {
    CODICE_COLLEZIONABILE NUMBER (12,0), 
    NOME_COLLEZIONABILE VARCHAR(70) NOT NULL,
    NOME_GIOCO VARCHAR(50) NOT NULL,
    CONSTRAINT PK_COLLEZIONABILE PRIMARY KEY (CODICE_COLLEZIONABILE,NOME_GIOCO),
    CONSTRAINT FK_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
}

CREATE TABLE OBIETTIVO{
    
    CODICE_OBIETTIVO NUMBER(10,0), --chiave entità debole
    NOME_OBIETTIVO VARCHAR(70) NOT NULL,
    NOME_GIOCO VARCHAR(50) NULL, --chiave dell'entità non debole 
    CONSTRAINT PK_OBIETTIVO PRIMARY KEY (CODICE_OBIETTIVO,NOME_GIOCO),
    CONSTRAINT FK_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
}

CREATE TABLE OTTIENE_COLLEZIONABILE{
    CODICE_COLLEZIONABILE NUMBER (12,0),
    USERNAME VARCHAR(50),
    DATA_OTTENIMENTO_COLLEZIONABILE DATE NOT NULL,

    CONSTRAINT PK_OTT_COLLEZIONABILE PRIMARY KEY (CODICE_COLLEZIONABILE,USERNAME),
    CONSTRAINT FK_OTTIENE_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_OTTIENE_COLLEZIONABILE FOREIGN KEY (CODICE_COLLEZIONABILE) REFERENCES COLLEZIONABILE(CODICE_COLLEZIONABILE) ON DELETE CASCADE }

