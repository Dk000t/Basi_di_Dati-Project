CREATE TABLE DLC(
    NOME_DLC VARCHAR(50),
    DATA_RILASCIO_DLC DATE NOT NULL,
    PREZZO_DLC NUMBER NOT NULL,
    NOME_GIOCO VARCHAR(50) NOT NULL

    PRIMARY KEY(NOME_DLC),
    CONSTRAINT FK_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE,
);

CREATE TABLE PAGAMENTO(
    CODICE_RICEVUTA_PAGAMENTO NUMBER(50),
    DATA_PAGAMENTO DATE NOT NULL,
    METODO_DI_PAGAMENTO VARCHAR(50) NOT NULL CHECK (METODO_DI_PAGAMENTO IN ('CARTA', 'PAYPAL')), 
    IMPORTO_PAGAMENTO NUMBER(255) NOT NULL,

    PRIMARY KEY(CODICE_RICEVUTA_PAGAMENTO),
    CONSTRAINT UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE

);

CREATE TABLE RISCATTA_DLC(
    NOME_DLC VARCHAR(50),
    CODICE_RICEVUTA_PAGAMENTO NUMBER(50),

    PRIMARY KEY (NOME_DLC, CODICE_RICEVUTA_PAGAMENTO),
    FOREIGN KEY (NOME_DLC) REFERENCES DLC(NOME_DLC),
    FOREIGN KEY (CODICE_RICEVUTA_PAGAMENTO) REFERENCES PAGAMENTO(CODICE_RICEVUTA_PAGAMENTO)
    
);

CREATE TABLE RISCATTA_GIOCO(
    NOME_GIOCO VARCHAR(50),
    CODICE_RICEVUTA_PAGAMENTO NUMBER(50),

    PRIMARY KEY (NOME_GIOCO, CODICE_RICEVUTA_PAGAMENTO),
    FOREIGN KEY (NOME_GIOCO) REFERENCES Gioco(NOME_GIOCO),
    FOREIGN KEY (CODICE_RICEVUTA_PAGAMENTO) REFERENCES PAGAMENTO(CODICE_RICEVUTA_PAGAMENTO)
);


