CREATE TABLE UTENTE (
    USERNAME VARCHAR PRIMARY KEY,
    EMAIL VARCHAR UNIQUE NOT NULL,
    DATA_ISCRIZIONE DATE NOT NULL
);

CREATE TABLE COMMUNITY (
    NOME_COMMUNITY VARCHAR PRIMARY KEY,
    USERNAME VARCHAR UNIQUE NOT NULL,
    DATA_CREAZIONE DATE NOT NULL,
    CONSTRAINT FK_COMMUNITY_OWNER FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME)
);

CREATE TABLE POST (
    NOME_COMMUNITY VARCHAR,
    CODICE_POST NUMBER NOT NULL,
    TITOLO_POST VARCHAR NOT NULL,
    USERNAME VARCHAR UNIQUE NOT NULL,
    DATA_PUBBLICAZIONE DATE NOT NULL,
    PRIMARY KEY(NOME_COMMUNITY, CODICE_POST),
    CONSTRAINT FK_COMMUNITY_NAME FOREIGN KEY (NOME_COMMUNITY) REFERENCES COMMUNITY(NOME_COMMUNITY),
    CONSTRAINT FK_POST_OWNER FOREIGN KEY(USERNAME) REFERENCES UTENTE(USERNAME)
);

CREATE TABLE GRUPPO (
    NOME_GRUPPO VARCHAR2 PRIMARY KEY,
    USERNAME VARCHAR UNIQUE NOT NULL,
    DATA_CREAZIONE DATE NOT NULL,
    CONSTRAINT FK_GROUP_OWNER FOREIGN KEY(USERNAME) REFERENCES UTENTE(USERNAME)
);

CREATE TABLE E_AMICO_DI (
    USERNAME_1 VARCHAR,
    USERNAME_2 VARCHAR,
    DATA_INIZIO DATE NOT NULL,
    PRIMARY KEY(USERNAME_1, USERNAME_2),
    CONSTRAINT PK_USER_1 FOREIGN KEY (USERNAME_1) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT PK_USER_2 FOREIGN KEY (USERNAME_2) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE
);

CREATE TABLE SEGUE (
    USERNAME VARCHAR,
    NOME_COMMUNITY VARCHAR,
    DATA_ISCRIZIONE DATE NOT NULL,
    PRIMARY KEY(USERNAME, NOME_COMMUNITY),
    CONSTRAINT PK_USER_COMMUNITY FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT PK_COMMUNITY_FOLLOWED FOREIGN KEY (NOME_COMMUNITY) REFERENCES COMMUNITY(NOME_COMMUNITY) ON DELETE CASCADE
);

CREATE TABLE FA_PARTE (
    USERNAME VARCHAR,
    NOME_GRUPPO VARCHAR,
    DATA_ADESIONE DATE NOT NULL,
    PRIMARY KEY(USERNAME, NOME_GRUPPO),
    CONSTRAINT PK_USER_GROUP FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT PK_GROUP_JOINED FOREIGN KEY (NOME_GRUPPO) REFERENCES GRUPPO(NOME_GRUPPO) ON DELETE CASCADE
);

CREATE TABLE LISTA_DESIDERI (
    USERNAME VARCHAR UNIQUE NOT NULL,
    NOME_GIOCO VARCHAR UNIQUE NOT NULL,
    DATA_INSERIMENTO DATE NOT NULL,
    CONSTRAINT PK_LIST_OWNER FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_GAME_NAME FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE GIOCO (
    NOME_GIOCO VARCHAR UNIQUE NOT NULL,
    DATA_RILASCIO DATE NOT NULL,
    GENERE VARCHAR NOT NULL,
    PREZZO NUMBER(4,0) NOT NULL,
    NOME_SVILUPPATORE VARCHAR UNIQUE NOT NULL,
    NOME_EDITORE VARCHAR UNIQUE NOT NULL,
    CONSTRAINT PK_GIOCO PRIMARY KEY (NOME_GIOCO),
    CONSTRAINT FK_EDITORE FOREIGN KEY (NOME_EDITORE) REFERENCES EDITORE(NOME_EDITORE) ON DELETE CASCADE,
    CONSTRAINT FK_CASA_SVILUPPATRICE FOREIGN KEY (NOME_SVILUPPATORE) REFERENCES CASA_SVILUPPATRICE(NOME_SVILUPPATORE) ON DELETE CASCADE
);

CREATE TABLE CASA_SVILUPPATRICE (
    NOME_SVILUPPATORE VARCHAR UNIQUE NOT NULL,
    ANNO_FONDAZIONE_SVILUPPATORE NUMBER (4,0) NOT NULL,
    NAZIONALITA_SVILUPPATORE VARCHAR NOT NULL,
    CONSTRAINT PK_CASA_SVILUPPATRICE PRIMARY KEY (NOME_SVILUPPATORE)
);

CREATE TABLE EDITORE (
    NOME_EDITORE VARCHAR UNIQUE NOT NULL,
    ANNO_FONDAZIONE_EDITORE NUMBER (4,0) NOT NULL,
    NAZIONALITA_EDITORE VARCHAR NOT NULL,
    CONSTRAINT PK_EDITORE PRIMARY KEY (NOME_EDITORE)
);

CREATE TABLE COLLEZIONABILE (
    CODICE_COLLEZIONABILE NUMBER (12,0),
    NOME_COLLEZIONABILE VARCHAR UNIQUE NOT NULL,
    NOME_GIOCO VARCHAR UNIQUE NOT NULL,
    CONSTRAINT PK_COLLEZIONABILE PRIMARY KEY (CODICE_COLLEZIONABILE, NOME_GIOCO),
    CONSTRAINT FK_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE OBIETTIVO (
    CODICE_OBIETTIVO NUMBER(10,0),
    NOME_OBIETTIVO VARCHAR UNIQUE NOT NULL,
    NOME_GIOCO VARCHAR UNIQUE NOT NULL,
    CONSTRAINT PK_OBIETTIVO PRIMARY KEY (CODICE_OBIETTIVO, NOME_GIOCO),
    CONSTRAINT FK_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE OTTIENE_COLLEZIONABILE (
    CODICE_COLLEZIONABILE NUMBER (12,0),
    USERNAME VARCHAR UNIQUE NOT NULL,
    DATA_OTTENIMENTO_COLLEZIONABILE DATE NOT NULL,
    CONSTRAINT PK_OTT_COLLEZIONABILE PRIMARY KEY (CODICE_COLLEZIONABILE, USERNAME),
    CONSTRAINT FK_OTTIENE_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_OTTIENE_COLLEZIONABILE FOREIGN KEY (CODICE_COLLEZIONABILE) REFERENCES COLLEZIONABILE(CODICE_COLLEZIONABILE) ON DELETE CASCADE
);

CREATE TABLE RAGGIUNGE_OBIETTIVO (
    CODICE_OBIETTIVO NUMBER (10,0),
    USERNAME VARCHAR UNIQUE NOT NULL, 
    DATA_OTTENIMENTO_OBIETTIVO DATE NOT NULL,

    CONSTRAINT PK_RAGG_OBIETTIVO PRIMARY KEY (CODICE_OBIETTIVO,USERNAME),
    CONSTRAINT FK_RAGGIUNGE_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_RAGGIUNGE_OBIETTIVO FOREIGN KEY (CODICE_OBIETTIVO) REFERENCES OBIETTIVO(CODICE_OBIETTIVO) ON DELETE CASCADE
);


CREATE TABLE RECENSIONE (
    COD_RECENSIONE NUMBER(7,0) PRIMARY KEY,
    TITOLO_RECENSIONE VARCHAR NOT NULL,
    VOTO_RECENSIONE NUMBER(10) NOT NULL,
    USERNAME VARCHAR UNIQUE NOT NULL,
    NOME_GIOCO VARCHAR UNIQUE NOT NULL,
    CONSTRAINT FK_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE KEY_GIOCO (
    CODICE_GIOCO NUMBER(20),
    DATA_SCADENZA DATE NOT NULL,
    USERNAME VARCHAR UNIQUE NOT NULL,
    NOME_GIOCO VARCHAR UNIQUE NOT NULL,
    PRIMARY KEY(CODICE_GIOCO),
    CONSTRAINT FK_UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE,
    CONSTRAINT FK_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE DLC (
    NOME_DLC VARCHAR,
    DATA_RILASCIO_DLC DATE NOT NULL,
    PREZZO_DLC NUMBER NOT NULL,
    NOME_GIOCO VARCHAR UNIQUE NOT NULL,
    PRIMARY KEY(NOME_DLC),
    CONSTRAINT FK_GIOCO FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO) ON DELETE CASCADE
);

CREATE TABLE PAGAMENTO (
    CODICE_RICEVUTA_PAGAMENTO NUMBER(50),
    DATA_PAGAMENTO DATE NOT NULL,
    METODO_DI_PAGAMENTO VARCHAR NOT NULL CHECK (METODO_DI_PAGAMENTO IN ('CARTA', 'PAYPAL')),
    IMPORTO_PAGAMENTO NUMBER(255) NOT NULL,
    PRIMARY KEY(CODICE_RICEVUTA_PAGAMENTO),
    CONSTRAINT UTENTE FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME) ON DELETE CASCADE
);

CREATE TABLE RISCATTA_DLC (
    USERNAME VARCHAR UNIQUE NOT NULL,
    NOME_DLC VARCHAR UNIQUE NOT NULL,
    CODICE_RICEVUTA_PAGAMENTO NUMBER(50) UNIQUE NOT NULL,
    PRIMARY KEY (NOME_DLC, CODICE_RICEVUTA_PAGAMENTO),
    FOREIGN KEY (NOME_DLC) REFERENCES DLC(NOME_DLC),
    FOREIGN KEY (CODICE_RICEVUTA_PAGAMENTO) REFERENCES PAGAMENTO(CODICE_RICEVUTA_PAGAMENTO),
    FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME)
);

CREATE TABLE RISCATTA_GIOCO (
    NOME_GIOCO VARCHAR UNIQUE NOT NULL,
    CODICE_RICEVUTA_PAGAMENTO NUMBER(50),
    USERNAME VARCHAR UNIQUE NOT NULL,
    PRIMARY KEY (NOME_GIOCO, CODICE_RICEVUTA_PAGAMENTO),
    FOREIGN KEY (NOME_GIOCO) REFERENCES GIOCO(NOME_GIOCO),
    FOREIGN KEY (CODICE_RICEVUTA_PAGAMENTO) REFERENCES PAGAMENTO(CODICE_RICEVUTA_PAGAMENTO),
    FOREIGN KEY (USERNAME) REFERENCES UTENTE(USERNAME)
);
